export function getVideosByModule(moduleId: string): VideoLesson[] {
  return videoLessons
    .filter((v) => v.moduleId === moduleId)
    .sort((a, b) => (a.watchOrder ?? 99) - (b.watchOrder ?? 99));
}

export function getVideoById(id: string): VideoLesson | undefined {
  return videoLessons.find((v) => v.id === id);
}

export function getAllConcepts(): string[] {
  return [...new Set(videoLessons.map((v) => v.concept))].sort();
}

export function searchVideos(query: string): VideoLesson[] {
  const q = query.toLowerCase();
  return videoLessons.filter(
    (v) =>
      v.title.toLowerCase().includes(q) ||
      v.concept.toLowerCase().includes(q) ||
      v.description.toLowerCase().includes(q) ||
      v.detailedExplanation.toLowerCase().includes(q) ||
      v.channel.toLowerCase().includes(q)
  );
}
